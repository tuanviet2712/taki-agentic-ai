#!/usr/bin/env python3
"""Sinh file <slug>Chunks.ts cho phu de karaoke tu danh sach cau da can chinh.

Cach dung:
1. Sua bien SENTS ben duoi: (start, end, "TEXT VIET HOA DA SUA LOI CHINH TA")
   - start/end lay tu output cua transcribe.py (ranh gioi cau)
   - text lay tu SCRIPT GOC (khong phai transcript whisper — whisper hay sai ten rieng)
2. python3 chunkgen.py > src/<slug>/<slug>Chunks.ts
   (sua ten bien export cho khop)

Thuat toan: chia 2-3 tu/chunk, khong bao gio chunk 1 tu,
timing noi suy deu theo so tu trong cau (sai so <0.3s).
"""

SENTS = [
    (0.08, 3.34, "VI DU CAU THU NHAT VIET HOA"),
    (4.28, 12.64, "THAY BANG CAC CAU THAT CUA BAN"),
]

EXPORT_NAME = "chunks"


def split_chunks(words):
    chunks, i, n = [], 0, len(words)
    while i < n:
        rem = n - i
        take = 3 if rem >= 3 and rem != 4 else 2
        if rem <= 3:
            take = rem
        if take == 1:  # gop tu le vao chunk truoc
            chunks[-1].extend(words[i : i + 1])
            i += 1
            continue
        chunks.append(words[i : i + take])
        i += take
    return chunks


def main() -> None:
    # Tuy chon: python3 chunkgen.py sents.json [ten_export] — sents.json = [[start, end, "TEXT"], ...]
    # (thay cho viec sua bien SENTS trong file; giu nguyen cach dung cu khi khong truyen tham so).
    import json, sys
    global SENTS, EXPORT_NAME
    if len(sys.argv) > 1:
        SENTS = [tuple(x) for x in json.load(open(sys.argv[1], encoding="utf-8"))]
        if len(sys.argv) > 2:
            EXPORT_NAME = sys.argv[2]
    print("// Auto-generated by chunkgen.py")
    print("export type Chunk = { start: number; end: number; words: string[] };")
    print(f"export const {EXPORT_NAME}: Chunk[] = [")
    total = 0
    for (s, e, text) in SENTS:
        w = text.split()
        per = (e - s) / len(w)
        t = s
        for c in split_chunks(w):
            dur = per * len(c)
            ws = ", ".join(f'"{x}"' for x in c)
            print(f"  {{ start: {round(t,2)}, end: {round(t+dur,2)}, words: [{ws}] }},")
            t += dur
            total += 1
    print("];")
    import sys
    print(f"// {total} chunks", file=sys.stderr)


if __name__ == "__main__":
    main()
